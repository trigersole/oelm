-- OELM raw blendshape batching and participant session recovery
-- Run once in the Supabase SQL Editor before deploying the matching frontend
-- and oelm-admin Edge Function.

begin;

-- These values let the frontend reconstruct the exact active-learning timeline
-- after a participant reconnects. Existing rows remain valid and use the
-- prediction timestamp fallback in the Edge Function.
alter table public.emotion_predictions
  add column if not exists active_elapsed_ms bigint,
  add column if not exists segment_id integer,
  add column if not exists segment_start_ts timestamptz;

create index if not exists emotion_predictions_session_timeline_idx
  on public.emotion_predictions (session_id, predicted_at);

-- One row stores up to 30 seconds of raw MediaPipe blendshape scores. The
-- values column is a two-dimensional JSON array: frames x 52 scores. Feature
-- names are deliberately not repeated in each batch; their fixed order is the
-- BLENDSHAPE_NAMES constant in src/app.js.
create table if not exists public.raw_blendshape_batches (
  id bigint generated by default as identity primary key,
  batch_id uuid not null default gen_random_uuid(),
  session_id text not null,
  participant_id text not null,
  cohort_id text not null,
  started_at timestamptz not null,
  ended_at timestamptz not null,
  capture_fps smallint not null default 5 check (capture_fps > 0 and capture_fps <= 30),
  frame_count smallint not null check (frame_count > 0 and frame_count <= 300),
  feature_count smallint not null default 52 check (feature_count = 52),
  values jsonb not null check (jsonb_typeof(values) = 'array'),
  created_at timestamptz not null default now(),
  check (ended_at >= started_at)
);

alter table public.raw_blendshape_batches
  add column if not exists batch_id uuid default gen_random_uuid();

update public.raw_blendshape_batches
set batch_id = gen_random_uuid()
where batch_id is null;

alter table public.raw_blendshape_batches
  alter column batch_id set not null;

create unique index if not exists raw_blendshape_batches_batch_id_key
  on public.raw_blendshape_batches (batch_id);

create index if not exists raw_blendshape_batches_session_time_idx
  on public.raw_blendshape_batches (session_id, started_at);

create index if not exists raw_blendshape_batches_participant_time_idx
  on public.raw_blendshape_batches (cohort_id, participant_id, started_at);

-- Raw training data is written and read only by the Edge Function's elevated
-- Supabase client. The browser's publishable key gets no direct table access.
alter table public.raw_blendshape_batches enable row level security;
revoke all on table public.raw_blendshape_batches from anon, authenticated;
revoke all on sequence public.raw_blendshape_batches_id_seq from anon, authenticated;

commit;
